// Generate deployable Deno modules from the tested application domain code.
import fs from "node:fs/promises";
for (const name of ["game", "rules", "types", "contracts"]) {
  let source = await fs.readFile(`lib/${name}.ts`, "utf8");
  source = source
    .replace('import "server-only";', "")
    .replace(
      'from "@/content/puzzles.json"',
      'from "./puzzles.json" with { type: "json" }',
    )
    .replace(/from "\.\/(rules|types)"/g, 'from "./$1.ts"')
    .replace(/from ['"]zod['"]/g, 'from "npm:zod@4.6.7"')
    .replace(
      "process.env.BLURT_BLOCKED_WORDS",
      'Deno.env.get("BLURT_BLOCKED_WORDS")',
    );
  await fs.writeFile(
    `supabase/functions/_shared/${name}.ts`,
    "// Generated by scripts/prepare-edge.mjs; edit lib/ instead.\n" + source,
  );
}
await fs.copyFile(
  "content/puzzles.json",
  "supabase/functions/_shared/puzzles.json",
);
const path = await import("node:path");
const entries = {};
for (const name of await fs.readdir("content/prepared"))
  if (/^a[0-9]+-[1-6]\.webp$/.test(name))
    entries[name] = (await fs.readFile(`content/prepared/${name}`)).toString(
      "base64",
    );
const assetImports = [],
  assetNames = [];
const catalog = JSON.parse(await fs.readFile("content/puzzles.json", "utf8"));
for (let i = 0; i < Math.min(10, catalog.length); i++) {
  const subset = Object.fromEntries(
    Object.entries(entries).filter(([name]) =>
      name.startsWith(catalog[i].id + "-"),
    ),
  );
  await fs.writeFile(
    `supabase/functions/_shared/assets-${i}.json`,
    JSON.stringify(subset),
  );
  assetImports.push(
    `import a${i} from './assets-${i}.json' with {type:'json'};`,
  );
  assetNames.push(`...a${i}`);
}
await fs.writeFile(
  "supabase/functions/_shared/assets.ts",
  assetImports.join("\n") +
    "\nexport default {" +
    assetNames.join(",") +
    "};\n",
);
const migrations = [];
for (const name of (await fs.readdir("supabase/migrations")).sort())
  if (name.endsWith(".sql"))
    migrations.push({
      name,
      sql: await fs.readFile(path.join("supabase/migrations", name), "utf8"),
    });
await fs.writeFile(
  "supabase/functions/_shared/migrations.json",
  JSON.stringify(migrations),
);
